import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(import.meta.dirname, "..");
const defaultOutputPath = resolve(
  repositoryRoot,
  "extensions/chrome/config.generated.js",
);
export const PRODUCTION_DASHBOARD_URL = "https://vault.favlock.app/";
export const PRODUCTION_API_URL = "https://api.favlock.app/";
export const PRODUCTION_EXTENSION_ID = "hcgkljieekclemmbcokchblkejkophad";

function parseEnvironmentFile(contents) {
  const values = {};

  for (const rawLine of contents.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;

    const separator = line.indexOf("=");
    if (separator < 1) continue;

    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }

  return values;
}

async function readEnvironmentFile(path) {
  try {
    return parseEnvironmentFile(await readFile(path, "utf8"));
  } catch (error) {
    if (error?.code === "ENOENT") return {};
    throw error;
  }
}

const testFileEnvironment =
  process.env.FAVLOCK_USE_TEST_ENV === "1"
      ? await readEnvironmentFile(
        resolve(repositoryRoot, ".env.test"),
      )
    : {};
const fileEnvironment = {
  ...testFileEnvironment,
  ...(await readEnvironmentFile(resolve(repositoryRoot, ".env"))),
  ...(await readEnvironmentFile(resolve(repositoryRoot, ".env.local"))),
};
const environment = { ...fileEnvironment, ...process.env };

function requireValue(name) {
  const value = environment[name]?.trim();
  if (!value) throw new Error(`${name} is required to configure the extension.`);
  return value;
}

function requireUrl(name) {
  const value = requireValue(name);
  const url = new URL(value);
  if (!['http:', 'https:'].includes(url.protocol)) {
    throw new Error(`${name} must use http or https.`);
  }
  return url.toString().replace(/\/$/, "");
}

export async function configureChromeExtension({
  target = "development",
  outputPath = defaultOutputPath,
} = {}) {
  if (!["development", "production"].includes(target)) {
    throw new Error(`Unknown Chrome extension target: ${target}`);
  }

  const production = target === "production";
  const apiUrl = production ? PRODUCTION_API_URL : requireUrl("VITE_API_URL");
  const generatedConfig = {
    target,
    dashboardUrl: production
      ? PRODUCTION_DASHBOARD_URL
      : requireUrl("VITE_DASHBOARD_URL"),
    apiUrl,
    extensionId: production ? PRODUCTION_EXTENSION_ID : null,
  };
  const output = `// Generated by npm run dev:chrome. Do not edit.\nexport const GENERATED_FAVLOCK_CONFIG = Object.freeze(${JSON.stringify(generatedConfig, null, 2)});\n`;

  await writeFile(outputPath, output, "utf8");
  console.log(
    `Configured the ${target} FavLock Chrome extension for ${generatedConfig.dashboardUrl}.`,
  );
  return generatedConfig;
}

const executedDirectly =
  process.argv[1] &&
  resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (executedDirectly) {
  await configureChromeExtension();
}
